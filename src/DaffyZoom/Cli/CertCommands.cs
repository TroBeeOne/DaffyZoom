using System.Security.Cryptography.X509Certificates;
using DaffyZoom.Tds;

namespace DaffyZoom.Cli;

/// <summary>
/// `daffyzoom cert ...` and `:cert ...` - the certificate clients see, and whether Windows trusts it.
///
/// From the command line it is the certificate DaffyZoom generated (in --config-dir's certs folder).
/// At the prompt it is the one being served, which may instead be a --cert-file certificate; that one
/// is shown, but never added to the trusted roots: DaffyZoom only vouches for a certificate it made.
/// </summary>
internal sealed class CertCommands(TextWriter output, X509Certificate2? served = null, string? suppliedPath = null)
{
    public static string Usage => """
          daffyzoom cert              the certificate clients see: where it is, the names it covers, when it
                                     expires, and whether Windows trusts it
          daffyzoom cert trust        (Windows) add it to your own trusted roots, for clients that check the
                                     certificate and cannot be told not to - Power BI's SQL Server connector
                                     among them. Windows asks you to confirm. Also: daffyzoom --trust-cert
          daffyzoom cert untrust      take every DaffyZoom certificate back out. Also: daffyzoom --untrust-cert
        """;

    public int Run(IReadOnlyList<string> args)
    {
        switch (args.Count == 0 ? "show" : args.Count == 1 ? args[0].ToLowerInvariant() : "")
        {
            case "show":
                return Show();
            case "trust":
                return Trust();
            case "untrust":
                return Untrust();
            default:
                output.WriteLine(Usage);
                return 1;
        }
    }

    private int Show()
    {
        using var loaded = served is null ? ServerCertificate.Existing() : null;
        var certificate = served ?? loaded;
        if (certificate is null)
        {
            output.WriteLine("  No certificate yet: DaffyZoom generates one the first time it serves ('daffyzoom cert trust'");
            output.WriteLine($"  generates it now). It will be {ServerCertificate.ResolvePath(null)}");
            return 0;
        }

        output.WriteLine();
        if (suppliedPath is not null)
        {
            output.WriteLine($"  certificate  {Path.GetFullPath(suppliedPath)}   (--cert-file)");
        }
        else
        {
            output.WriteLine($"  certificate  {ServerCertificate.ResolvePath(null)}   (generated by DaffyZoom)");
            output.WriteLine($"  public half  {ServerCertificate.PublicPath(null)}");
        }
        output.WriteLine($"  names        {string.Join(", ", ServerCertificate.Names(certificate))}");
        output.WriteLine($"  expires      {certificate.NotAfter:yyyy-MM-dd}");
        output.WriteLine($"  thumbprint   {certificate.Thumbprint}");
        output.WriteLine($"  trusted      {TrustState(certificate)}");

        if (suppliedPath is null && CertificateTrust.Superseded(certificate) is > 0 and var stale)
            output.WriteLine($"               and {stale} older DaffyZoom certificate(s), no longer used - ':cert untrust' clears them");
        output.WriteLine();
        return 0;
    }

    private string TrustState(X509Certificate2 certificate)
    {
        if (suppliedPath is not null)
        {
            // Someone else's certificate: trusted or not by its own issuer, which only a chain says.
            using var chain = new X509Chain();
            chain.ChainPolicy.RevocationMode = X509RevocationMode.NoCheck;
            return chain.Build(certificate)
                ? "yes - this machine accepts it"
                : $"no - {string.Join("; ", chain.ChainStatus.Select(s => s.StatusInformation.Trim()).Distinct())}";
        }

        if (!OperatingSystem.IsWindows())
            return "not checked - trusting is only done on Windows; use TrustServerCertificate=True, or Encrypt=Strict with the .cer";

        return CertificateTrust.TrustedIn(certificate) switch
        {
            StoreLocation.CurrentUser => $"yes, for this Windows user ({CertificateTrust.Describe(StoreLocation.CurrentUser)})",
            StoreLocation.LocalMachine => $"yes, for every account on this machine ({CertificateTrust.Describe(StoreLocation.LocalMachine)})",
            _ => "no - clients that check the certificate refuse it until 'cert trust'",
        };
    }

    private int Trust()
    {
        if (suppliedPath is not null)
        {
            output.WriteLine("  This certificate came from --cert-file, and DaffyZoom only adds the certificate it generated.");
            output.WriteLine("  One from a certificate authority needs no adding once that authority is trusted.");
            return 1;
        }

        var certificate = served ?? ServerCertificate.Load(null, null, regenerate: false);
        try
        {
            return CertificateTrust.Trust(certificate, output) ? 0 : 1;
        }
        finally
        {
            if (!ReferenceEquals(certificate, served)) certificate.Dispose();
        }
    }

    private int Untrust()
    {
        // The generated certificate, even while serving a --cert-file one: that is the one DaffyZoom
        // may have added, and a supplied certificate trusted some other way is not ours to remove.
        using var loaded = served is null || suppliedPath is not null ? ServerCertificate.Existing() : null;
        CertificateTrust.Untrust(suppliedPath is null ? served ?? loaded : loaded, output);
        return 0;
    }
}
